import { expect,test } from '@playwright/test'

test('admin completes a reviewed query through the local UI and API',async({page})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Create the administrator'})).toBeVisible()
  await page.getByLabel('Account name').fill('e2e-admin')
  await page.getByLabel('Password').fill('Local-e2e-password-2026!')
  await page.getByLabel('Administrator setup token').fill('local-e2e-setup-secret-2026-11-15')
  await page.getByRole('button',{name:'Create administrator'}).click()

  await expect(page.getByRole('button',{name:'Access and security'})).toBeVisible()
  await page.getByLabel('Ask your data a question').fill('How many orders are there?')
  await page.getByRole('button',{name:'Run question'}).click()

  await expect(page.getByRole('heading',{name:'Review the tables before we write SQL'})).toBeVisible()
  await page.getByRole('button',{name:'Confirm tables and continue'}).click()
  await expect(page.getByRole('heading',{name:'Review SQL before reading data'})).toBeVisible()
  await page.getByRole('button',{name:'Approve SQL and run'}).click()

  const answer=page.locator('.query-entry')
  await expect(answer).toContainText('There are 25 orders.',{timeout:20000})
  await expect(answer).toContainText('SELECT COUNT(*) FROM orders;')
  await expect(answer).toContainText('Executed against your database')

  await page.getByRole('button',{name:'Visualize this result'}).click()
  await expect(page.locator('.visualization-kpi strong')).toHaveText('25')
  await page.getByLabel('Ask your data a question').fill('Show the number of orders by status.')
  await page.getByRole('button',{name:'Run question'}).click()
  await page.getByRole('heading',{name:'Review the tables before we write SQL'}).waitFor()
  await page.getByRole('button',{name:'Confirm tables and continue'}).click()
  await page.getByRole('heading',{name:'Review SQL before reading data'}).waitFor()
  await page.getByRole('button',{name:'Approve SQL and run'}).click()
  await expect(page.locator('.query-entry').last()).toContainText('Orders by status are shown.')
  await page.getByRole('button',{name:'Visualize this result'}).click()
  await expect(page.locator('.interactive-chart .main-svg').first()).toBeVisible({timeout:30000})
  await expect(page.locator('.interactive-chart .barlayer .point')).not.toHaveCount(0)
  await expect(page.locator('.modebar-btn[data-title*="Download"]')).toHaveCount(0)
  await page.locator('.interactive-chart').scrollIntoViewIfNeeded()
  await page.screenshot({path:'../outputs/visualization-ui.png'})
  await page.getByLabel('Chart presentation').last().selectOption('static')
  await page.getByRole('button',{name:'Visualize this result'}).click()
  await expect(page.locator('.static-chart')).toBeVisible({timeout:20000})
  await expect(page.locator('.visualization-content').last()).toContainText('seaborn')
  await page.locator('.static-chart').scrollIntoViewIfNeeded()
  await page.screenshot({path:'../outputs/visualization-static-ui.png'})

  await page.getByRole('button',{name:'Domain knowledge',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Domain knowledge.'})).toBeVisible()
  await page.getByLabel('Knowledge domain').selectOption('sales')
  await page.getByRole('button',{name:'Create definition'}).click()
  await page.getByLabel('Name',{exact:true}).fill('Order lifecycle')
  await page.getByLabel('Business definition').fill('Order status terminology for the reporting team. Business meaning reviewed independently.')
  await page.getByLabel('Representative business review questions, one per line').fill('Which order statuses belong in our report?')
  await page.getByRole('button',{name:'Save draft'}).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await page.getByText('Version history and review actions').click()
  await page.getByRole('button',{name:'Validate metadata'}).click()
  await expect(page.getByRole('status')).toContainText('No query was executed')
  await page.getByRole('button',{name:'Submit for review'}).click()
  await page.getByLabel('Review evidence, independent checks and limitations').fill('Reviewed against the team reporting specification; this demo is not an independent answer-accuracy evaluation.')
  await page.getByRole('checkbox',{name:/I reviewed the business meaning/}).check()
  await page.getByRole('button',{name:'Publish revision'}).click()
  await expect(page.getByText('Active published revision: 1')).toBeVisible()
  await page.getByRole('heading',{name:'Domain knowledge.'}).scrollIntoViewIfNeeded()
  await page.screenshot({path:'../outputs/domain-knowledge-workspace.png',fullPage:true})
})
